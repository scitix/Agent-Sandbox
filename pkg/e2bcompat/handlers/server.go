func (s *Server) GetApiKeys(ctx context.Context, _ e2bgen.GetApiKeysRequestObject) (e2bgen.GetApiKeysResponseObject, error) {
	auth := authFrom(ctx)
	result, appErr := s.apikey.ListByTeamAndUser(ctx, auth.Team, auth.User)
	if appErr != nil {
		return e2bgen.GetApiKeys500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespAppErr(ctx, appErr))}, nil
	}

	keys := make(e2bgen.GetApiKeys200JSONResponse, 0, len(result.Items))
	for _, item := range result.Items {
		k := e2bgen.TeamAPIKey{
			Name:      item.Description,
			CreatedAt: item.IssuedAt,
			Mask: e2bgen.IdentifierMaskingDetails{
				Prefix:      item.ShortName,
				ValueLength: 16,
			},
		}
		keys = append(keys, k)
	}
	return keys, nil
}

func (s *Server) PostApiKeys(ctx context.Context, req e2bgen.PostApiKeysRequestObject) (e2bgen.PostApiKeysResponseObject, error) {
	if req.Body == nil {
		return e2bgen.PostApiKeys401JSONResponse{N401JSONResponse: e2bgen.N401JSONResponse(errRespCode(400, "request body required"))}, nil
	}

	auth := authFrom(ctx)
	result, appErr := s.apikey.Create(ctx, apidomain.CreateAPIKeyInput{
		Namespace:   auth.Namespace,
		User:        auth.User,
		Team:        auth.Team,
		Description: req.Body.Name,
	})
	if appErr != nil {
		return e2bgen.PostApiKeys500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespAppErr(ctx, appErr))}, nil
	}

	resp := e2bgen.CreatedTeamAPIKey{
		Name:      req.Body.Name,
		Key:       result.RawToken,
		CreatedAt: result.IssuedAt,
		Mask: e2bgen.IdentifierMaskingDetails{
			Prefix:      result.KeyID,
			ValueLength: 16,
		},
	}
	return e2bgen.PostApiKeys201JSONResponse(resp), nil
}

