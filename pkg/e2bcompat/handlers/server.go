// imageOverrideMetaKey is the reserved metadata key used to override the sandbox main container image
// via the E2B-compatible API. This key is consumed internally and will NOT be forwarded to sandbox metadata.
const imageOverrideMetaKey = "agentbox.scitix.ai/image"

// startupTimeoutMetaKey is the reserved metadata key used to override the sandbox startup timeout
// via the E2B-compatible API. Value is in seconds (integer string). This key is consumed internally
// and will NOT be forwarded to sandbox metadata.
const startupTimeoutMetaKey = "agentbox.scitix.ai/startup-timeout"

func (s *Server) PostSandboxes(ctx context.Context, req e2bgen.PostSandboxesRequestObject) (e2bgen.PostSandboxesResponseObject, error) {
	if req.Body == nil || strings.TrimSpace(req.Body.TemplateID) == "" {
		return e2bgen.PostSandboxes400JSONResponse{N400JSONResponse: e2bgen.N400JSONResponse(errRespCode(400, "templateID is required"))}, nil
	}

	parsed := cluster.ParsePoolRef(req.Body.TemplateID)
	if parsed.PoolName == "" {
		return e2bgen.PostSandboxes400JSONResponse{N400JSONResponse: e2bgen.N400JSONResponse(errRespCode(400, "templateID is required"))}, nil
	}

	auth := authFrom(ctx)
	input := apidomain.CreateSandboxInput{
		ClusterID: parsed.ClusterID,
		PoolName:  parsed.PoolName,
		Namespace: auth.Namespace,
		Image:     parsed.ImageOverride, // Option B: image embedded via "poolName//image" syntax
	}
	if req.Body.Metadata != nil {
		input.Metadata = map[string]string(*req.Body.Metadata)
		// Image override: new key takes priority over legacy key.
		// Both keys are consumed and NOT forwarded to sandbox metadata.
		if img, ok := input.Metadata[imageOverrideMetaKey]; ok && img != "" {
			input.Image = img
			delete(input.Metadata, imageOverrideMetaKey)
		}
		// Startup timeout override via metadata (value in seconds).
		// Consumed and NOT forwarded to sandbox metadata.
		if raw, ok := input.Metadata[startupTimeoutMetaKey]; ok && raw != "" {
			if secs, err := strconv.Atoi(raw); err == nil && secs > 0 {
				input.StartupTimeout = time.Duration(secs) * time.Second
			}
			delete(input.Metadata, startupTimeoutMetaKey)
		}
	}
	if req.Body.EnvVars != nil && len(*req.Body.EnvVars) > 0 {
		input.PostStartHooks = []apidomain.PostStartHookAction{{
			HTTPPost: &apidomain.HTTPPostHookAction{
				Port: 49983,
				Path: "/init",
				Body: map[string]any{
					"envVars": map[string]string(*req.Body.EnvVars),
				},
			},
		}}
	}
	if req.Body.Timeout != nil && *req.Body.Timeout > 0 {
		input.IdleTimeout = time.Duration(*req.Body.Timeout) * time.Second
	}
	// Inject team/user from auth into labels so they are recorded on the pod
	// and metrics (agentbox_sandbox_create_total) carry the correct dimensions.
	input.Labels = make(map[string]string)
	if auth.Team != "" {
		input.Labels[agentsv1alpha1.LabelTeam] = auth.Team
	}
	if auth.User != "" {
		input.Labels[agentsv1alpha1.LabelUser] = auth.User
	}

	// Cross-cluster forwarding: if the pool references a remote cluster, forward
	// the request to that cluster's E2B API.
	if s.isCrossCluster(input.ClusterID) {
		s.forwarder.Forward(httpctx.GinFromCtx(ctx), input.ClusterID, service.URLKindE2B, jsonBody(req.Body))
		return nil, nil
	}

	result, appErr := s.sandbox.Create(ctx, input)
	if appErr != nil {
		switch appErr.Code {
		case apidomain.ErrCodeNotFound:
			return e2bgen.PostSandboxes400JSONResponse{N400JSONResponse: e2bgen.N400JSONResponse(errRespCode(400, appErr.Message))}, nil
		default:
			return e2bgen.PostSandboxes500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespAppErr(ctx, appErr))}, nil
		}
	}

	sb := s.domainSandboxToE2BSandbox(ctx, result, auth.Namespace)
	return e2bgen.PostSandboxes201JSONResponse(sb), nil
}

func (s *Server) GetSandboxes(ctx context.Context, _ e2bgen.GetSandboxesRequestObject) (e2bgen.GetSandboxesResponseObject, error) {
	auth := authFrom(ctx)
	result, appErr := s.sandbox.List(ctx, apidomain.ListSandboxesFilter{
		Namespace: auth.Namespace,
		Team:      auth.Team,
		User:      auth.User,
		Limit:     0,
	})
	if appErr != nil {
		return e2bgen.GetSandboxes500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespAppErr(ctx, appErr))}, nil
	}

	poolMap := s.loadPoolMap(ctx, auth.Namespace)

	items := make([]e2bgen.ListedSandbox, 0, len(result.Items))
	for i := range result.Items {
		sb := &result.Items[i]
		pool := poolMap[sb.PoolName]
		items = append(items, domainSandboxToListedSandbox(sb, pool))
	}

	return e2bgen.GetSandboxes200JSONResponse(items), nil
}

func (s *Server) GetSandboxesSandboxID(ctx context.Context, req e2bgen.GetSandboxesSandboxIDRequestObject) (e2bgen.GetSandboxesSandboxIDResponseObject, error) {
	auth := authFrom(ctx)
	sandboxID := string(req.SandboxID)
	if clusterID, _ := cluster.SplitSandboxID(sandboxID); s.isCrossCluster(clusterID) {
		s.forwarder.Forward(httpctx.GinFromCtx(ctx), clusterID, service.URLKindE2B, nil)
		return nil, nil
	}
	result, appErr := s.sandbox.Get(ctx, auth.Namespace, sandboxID)
	if appErr != nil {
		if appErr.Code == apidomain.ErrCodeNotFound {
			return e2bgen.GetSandboxesSandboxID404JSONResponse{N404JSONResponse: e2bgen.N404JSONResponse(errRespCode(404, appErr.Message))}, nil
		}
		return e2bgen.GetSandboxesSandboxID500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespAppErr(ctx, appErr))}, nil
	}

	detail := s.domainSandboxToSandboxDetail(ctx, result, auth.Namespace)
	return e2bgen.GetSandboxesSandboxID200JSONResponse(detail), nil
}

func (s *Server) DeleteSandboxesSandboxID(ctx context.Context, req e2bgen.DeleteSandboxesSandboxIDRequestObject) (e2bgen.DeleteSandboxesSandboxIDResponseObject, error) {
	auth := authFrom(ctx)
	sandboxID := string(req.SandboxID)
	if clusterID, _ := cluster.SplitSandboxID(sandboxID); s.isCrossCluster(clusterID) {
		s.forwarder.Forward(httpctx.GinFromCtx(ctx), clusterID, service.URLKindE2B, nil)
		return nil, nil
	}
	_, appErr := s.sandbox.Delete(ctx, auth.Namespace, sandboxID)
	if appErr != nil {
		if appErr.Code == apidomain.ErrCodeNotFound {
			return e2bgen.DeleteSandboxesSandboxID404JSONResponse{N404JSONResponse: e2bgen.N404JSONResponse(errRespCode(404, appErr.Message))}, nil
		}
		return e2bgen.DeleteSandboxesSandboxID500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespAppErr(ctx, appErr))}, nil
	}
	return e2bgen.DeleteSandboxesSandboxID204Response{}, nil
}

func (s *Server) PostSandboxesSandboxIDTimeout(ctx context.Context, req e2bgen.PostSandboxesSandboxIDTimeoutRequestObject) (e2bgen.PostSandboxesSandboxIDTimeoutResponseObject, error) {
	if req.Body == nil || req.Body.Timeout <= 0 {
		return e2bgen.PostSandboxesSandboxIDTimeout401JSONResponse{N401JSONResponse: e2bgen.N401JSONResponse(errRespCode(400, "timeout must be a positive integer (seconds)"))}, nil
	}

	auth := authFrom(ctx)
	sandboxID := string(req.SandboxID)
	timeout := time.Duration(req.Body.Timeout) * time.Second
	if clusterID, _ := cluster.SplitSandboxID(sandboxID); s.isCrossCluster(clusterID) {
		s.forwarder.Forward(httpctx.GinFromCtx(ctx), clusterID, service.URLKindE2B, jsonBody(req.Body))
		return nil, nil
	}
	if appErr := s.sandbox.SetTimeout(ctx, auth.Namespace, sandboxID, timeout); appErr != nil {
		if appErr.Code == apidomain.ErrCodeNotFound {
			return e2bgen.PostSandboxesSandboxIDTimeout404JSONResponse{N404JSONResponse: e2bgen.N404JSONResponse(errRespCode(404, appErr.Message))}, nil
		}
		return e2bgen.PostSandboxesSandboxIDTimeout500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespAppErr(ctx, appErr))}, nil
	}
	return e2bgen.PostSandboxesSandboxIDTimeout204Response{}, nil
}

func (s *Server) PostSandboxesSandboxIDRefreshes(ctx context.Context, req e2bgen.PostSandboxesSandboxIDRefreshesRequestObject) (e2bgen.PostSandboxesSandboxIDRefreshesResponseObject, error) {
	// Refreshes = extend idle timeout to keep the sandbox alive.
	if req.Body != nil && req.Body.Duration != nil && *req.Body.Duration > 0 {
		auth := authFrom(ctx)
		sandboxID := string(req.SandboxID)
		timeout := time.Duration(*req.Body.Duration) * time.Second
		if clusterID, _ := cluster.SplitSandboxID(sandboxID); s.isCrossCluster(clusterID) {
			s.forwarder.Forward(httpctx.GinFromCtx(ctx), clusterID, service.URLKindE2B, jsonBody(req.Body))
			return nil, nil
		}
		if appErr := s.sandbox.SetTimeout(ctx, auth.Namespace, sandboxID, timeout); appErr != nil {
			if appErr.Code == apidomain.ErrCodeNotFound {
				return e2bgen.PostSandboxesSandboxIDRefreshes404JSONResponse{N404JSONResponse: e2bgen.N404JSONResponse(errRespCode(404, appErr.Message))}, nil
			}
			return e2bgen.PostSandboxesSandboxIDRefreshes401JSONResponse{N401JSONResponse: e2bgen.N401JSONResponse(errRespCode(500, appErr.Message))}, nil
		}
	}
	return e2bgen.PostSandboxesSandboxIDRefreshes204Response{}, nil
}

