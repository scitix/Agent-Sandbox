func (s *Server) GetTemplates(ctx context.Context, _ e2bgen.GetTemplatesRequestObject) (e2bgen.GetTemplatesResponseObject, error) {
	if s.k8sClient == nil {
		return e2bgen.GetTemplates500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errResp("k8s client not available"))}, nil
	}

	auth := authFrom(ctx)
	poolList := &agentsv1alpha1.SandboxPoolList{}
	if err := s.k8sClient.List(ctx, poolList, client.InNamespace(auth.Namespace)); err != nil {
		return e2bgen.GetTemplates500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespServer(ctx, err, err.Error()))}, nil
	}

	templates := make(e2bgen.GetTemplates200JSONResponse, 0, len(poolList.Items))
	for i := range poolList.Items {
		templates = append(templates, poolToE2BTemplate(&poolList.Items[i]))
	}
	return templates, nil
}

func (s *Server) GetTemplatesTemplateID(ctx context.Context, req e2bgen.GetTemplatesTemplateIDRequestObject) (e2bgen.GetTemplatesTemplateIDResponseObject, error) {
	if s.k8sClient == nil {
		return e2bgen.GetTemplatesTemplateID500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errResp("k8s client not available"))}, nil
	}

	auth := authFrom(ctx)
	pool := &agentsv1alpha1.SandboxPool{}
	if err := s.k8sClient.Get(ctx, client.ObjectKey{Namespace: auth.Namespace, Name: string(req.TemplateID)}, pool); err != nil {
		if errors.IsNotFound(err) {
			return e2bgen.GetTemplatesTemplateID401JSONResponse{N401JSONResponse: e2bgen.N401JSONResponse(errRespCode(404, "template not found"))}, nil
		}
		return e2bgen.GetTemplatesTemplateID500JSONResponse{N500JSONResponse: e2bgen.N500JSONResponse(errRespServer(ctx, err, err.Error()))}, nil
	}

	// GetTemplatesTemplateID200JSONResponse is TemplateWithBuilds (not a wrapper)
	// TemplateWithBuilds has its own fields, not a Template subfield
	tmpl := poolToE2BTemplate(pool)
	result := e2bgen.TemplateWithBuilds{
		TemplateID: tmpl.TemplateID,
		Public:     tmpl.Public,
		SpawnCount: tmpl.SpawnCount,
		Aliases:    tmpl.Aliases,
		Names:      tmpl.Names,
		CreatedAt:  tmpl.CreatedAt,
		UpdatedAt:  tmpl.UpdatedAt,
		Builds:     []e2bgen.TemplateBuild{},
	}
	return e2bgen.GetTemplatesTemplateID200JSONResponse(result), nil
}

// poolToE2BTemplate converts an AgentBox SandboxPool to an E2B Template.
func poolToE2BTemplate(pool *agentsv1alpha1.SandboxPool) e2bgen.Template {
	return e2bdomain.ToE2BTemplate(pool)
}

